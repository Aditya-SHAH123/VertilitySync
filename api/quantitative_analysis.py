"""
Quantitative imaging analysis for a reconstructed chest CT study.

Turns a reconstructed HU volume plus a lung segmentation into a structured,
spatially organised set of measurements. Every value here is either read from
DICOM metadata or computed deterministically from the voxel data - nothing is
estimated, inferred, or generated by a model.

WHAT THIS MODULE DOES NOT DO
    It does not detect, classify, or name any disease or radiological finding.
    Sections that would require capabilities this application does not have
    (lobe segmentation, finding detection, airway and vessel segmentation,
    texture radiomics, prior-study registration) return an explicit
    NOT_AVAILABLE status with the reason, and never a placeholder number.

PROVENANCE
    Every section carries a `provenance` block naming where its numbers came
    from - `dicom_metadata`, `voxel_computation`, or `segmentation` - so a
    reader can tell a directly-measured quantity from one that inherits the
    segmentation's assumptions. There is currently no `model_output`
    provenance anywhere in this module, because no model is used.

UNITS
    Volumes are millilitres (1 mL = 1000 mm^3), computed from the physical
    voxel volume, never from voxel counts alone. Distances are millimetres.
    Densities are Hounsfield units.
"""

from datetime import datetime, timezone

import numpy as np
from scipy import ndimage

from density_regions import analyze_density_regions

ANALYSIS_VERSION = "1.0.0"

# Status vocabulary used throughout the result.
OK = "OK"
WARNING = "WARNING"
FAILED = "FAILED"
NOT_AVAILABLE = "NOT_AVAILABLE"
NOT_EVALUATED = "NOT_EVALUATED"

# Histogram: fixed range and bin width so histograms are directly comparable
# between studies and between regions of the same study.
HIST_MIN_HU = -1024.0
HIST_MAX_HU = 200.0
HIST_BIN_WIDTH_HU = 8.0

# Distance from the pleural surface used to define the peripheral band. This
# is a geometric convention for describing WHERE tissue sits, not a
# diagnostic threshold.
PERIPHERAL_BAND_MM = 20.0
SUBPLEURAL_BAND_MM = 10.0

PERCENTILES = (5, 10, 25, 50, 75, 90, 95)


def _now():
    return datetime.now(timezone.utc).isoformat()


def _provenance(source, method, **extra):
    p = {
        "source": source,
        "method": method,
        "analysis_version": ANALYSIS_VERSION,
        "computed_at": _now(),
    }
    p.update(extra)
    return p


def _unavailable(reason, requires=None):
    """A section that cannot be computed. Carries the reason and what it would
    take to enable it - never a number."""
    block = {"status": NOT_AVAILABLE, "reason": reason}
    if requires:
        block["requires"] = requires
    return block


# ---------------------------------------------------------------------------
# Density statistics
# ---------------------------------------------------------------------------

def hu_statistics(hu_volume, mask, voxel_volume_ml):
    """Descriptive statistics of the HU values inside `mask`.

    Definitions are the standard ones: the mean is the arithmetic mean, the
    standard deviation is the population (ddof=0) standard deviation, and
    percentiles use linear interpolation between order statistics
    (numpy's default). Skewness and kurtosis are the third and fourth
    standardised moments, with kurtosis reported as EXCESS kurtosis (normal
    distribution = 0).
    """
    values = hu_volume[mask]
    n = int(values.size)
    if n == 0:
        return {"status": NOT_AVAILABLE, "reason": "The region contains no voxels."}

    values = values.astype(np.float64, copy=False)
    mean = float(values.mean())
    std = float(values.std(ddof=0))
    pcts = np.percentile(values, PERCENTILES)

    if std > 1e-9:
        z = (values - mean) / std
        skewness = float((z ** 3).mean())
        kurtosis_excess = float((z ** 4).mean() - 3.0)
    else:
        skewness = 0.0
        kurtosis_excess = 0.0

    return {
        "status": OK,
        "voxel_count": n,
        "volume_ml": round(n * voxel_volume_ml, 2),
        "mean_hu": round(mean, 2),
        "median_hu": round(float(np.median(values)), 2),
        "std_hu": round(std, 2),
        "min_hu": round(float(values.min()), 2),
        "max_hu": round(float(values.max()), 2),
        "percentiles_hu": {f"p{p}": round(float(v), 2) for p, v in zip(PERCENTILES, pcts)},
        # First-order radiomic descriptors. These are shape-free intensity
        # statistics with standard definitions; they are NOT texture features.
        "skewness": round(skewness, 4),
        "kurtosis_excess": round(kurtosis_excess, 4),
    }


def hu_histogram(hu_volume, mask):
    """Fixed-grid histogram of HU values inside `mask`.

    The grid is identical for every region and every study
    (HIST_MIN_HU..HIST_MAX_HU at HIST_BIN_WIDTH_HU), so histograms can be
    overlaid or compared directly. Values outside the range are counted in
    the reported underflow/overflow totals rather than silently dropped.
    """
    values = hu_volume[mask]
    if values.size == 0:
        return {"status": NOT_AVAILABLE, "reason": "The region contains no voxels."}

    n_bins = int(round((HIST_MAX_HU - HIST_MIN_HU) / HIST_BIN_WIDTH_HU))
    counts, edges = np.histogram(values, bins=n_bins, range=(HIST_MIN_HU, HIST_MAX_HU))
    under = int((values < HIST_MIN_HU).sum())
    over = int((values > HIST_MAX_HU).sum())

    return {
        "status": OK,
        "bin_width_hu": HIST_BIN_WIDTH_HU,
        "range_hu": [HIST_MIN_HU, HIST_MAX_HU],
        "bin_edges_hu": [round(float(e), 2) for e in edges],
        "counts": [int(c) for c in counts],
        "underflow_count": under,
        "overflow_count": over,
        "total_voxels": int(values.size),
    }


