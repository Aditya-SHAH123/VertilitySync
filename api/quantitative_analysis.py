# Top-level analysis
# ---------------------------------------------------------------------------

def analyze_study(hu_volume, hu_available_per_slice, geometry, segmentation, summary,
                   series_status="PASS"):
    """Builds the full structured analysis for one study.

    `segmentation` may be None (not yet run) or a failed result - in that
    case every anatomy-dependent section reports NOT_AVAILABLE with the
    reason, and only scan quality is produced.
    """
    spacing = geometry.spacing_mm
    voxel_volume_mm3 = float(spacing[0]) * float(spacing[1]) * float(spacing[2])
    voxel_volume_ml = voxel_volume_mm3 / 1000.0

    seg_ok = segmentation is not None and getattr(segmentation, "success", False)
    seg_stats = dict(getattr(segmentation, "stats", {})) if segmentation is not None else {}

    result = {
        "analysis_version": ANALYSIS_VERSION,
        "generated_at": _now(),
        "voxel_volume_mm3": round(voxel_volume_mm3, 6),
        "spacing_mm": [round(float(v), 4) for v in spacing],
        "scan_quality": assess_scan_quality(summary, seg_stats if seg_ok else None,
                                             geometry, series_status),
        "warnings": [],
    }

    if not seg_ok:
        reason = ("Lung segmentation has not been run for this study."
                  if segmentation is None else
                  "Lung segmentation did not pass its plausibility checks, so no anatomy-dependent "
                  "measurement can be trusted.")
        for key in ("lung_metrics", "density_metrics", "histogram", "regional_metrics",
                     "asymmetry", "lobe_metrics", "findings", "airways", "vasculature",
                     "longitudinal"):
            result[key] = _unavailable(reason, requires="A successful lung segmentation.")
        result["warnings"].append(reason)
        return result

    mask = segmentation.mask
    left = segmentation.left_mask
    right = segmentation.right_mask
    has_sides = left is not None and right is not None

    # ---- 2. total lung quantification ----
    total_voxels = int(mask.sum())
    total_ml = total_voxels * voxel_volume_ml
    lung_metrics = {
        "status": OK,
        "total_lung_volume_ml": round(total_ml, 1),
        "voxel_count": total_voxels,
        "left_lung_volume_ml": round(float(left.sum()) * voxel_volume_ml, 1) if has_sides else None,
        "right_lung_volume_ml": round(float(right.sum()) * voxel_volume_ml, 1) if has_sides else None,
        "left_right_available": bool(has_sides),
        "left_right_method": seg_stats.get("left_right_method"),
        "volume_definition": "voxel count x (x spacing x y spacing x z spacing), converted to mL.",
        "provenance": _provenance("segmentation", "Voxel count within the lung mask scaled by "
                                                   "physical voxel volume.",
                                   segmentation_method=segmentation.method,
                                   segmentation_method_version=segmentation.method_version),
    }
    if has_sides:
        lv = lung_metrics["left_lung_volume_ml"]
        rv = lung_metrics["right_lung_volume_ml"]
        lung_metrics["left_fraction"] = round(lv / total_ml, 4) if total_ml else None
        lung_metrics["right_fraction"] = round(rv / total_ml, 4) if total_ml else None
        lung_metrics["left_right_ratio"] = round(lv / rv, 4) if rv else None
    result["lung_metrics"] = lung_metrics

    # ---- 4. density analysis ----
    density = {
        "status": OK,
        "whole_lungs": hu_statistics(hu_volume, mask, voxel_volume_ml),
        "provenance": _provenance("voxel_computation",
                                   "Descriptive statistics of HU values inside the segmentation mask.",
                                   percentiles=list(PERCENTILES),
                                   percentile_method="numpy linear interpolation",
                                   std_ddof=0, kurtosis="excess (normal = 0)"),
    }
    if has_sides:
        density["left_lung"] = hu_statistics(hu_volume, left, voxel_volume_ml)
        density["right_lung"] = hu_statistics(hu_volume, right, voxel_volume_ml)
    result["density_metrics"] = density

    histograms = {"whole_lungs": hu_histogram(hu_volume, mask)}
    if has_sides:
        histograms["left_lung"] = hu_histogram(hu_volume, left)
        histograms["right_lung"] = hu_histogram(hu_volume, right)
    result["histogram"] = {
        "status": OK,
        "regions": histograms,
        "provenance": _provenance("voxel_computation",
                                   "Fixed-grid histogram so regions and studies are directly comparable.",
                                   bin_width_hu=HIST_BIN_WIDTH_HU, range_hu=[HIST_MIN_HU, HIST_MAX_HU]),
    }

    # ---- 5. regional distribution ----
    regional = {"status": OK,
                "provenance": _provenance("voxel_computation",
                                           "Geometric decomposition of the lung mask; positional only.")}

    zones, zone_meta = superior_inferior_zones(mask, geometry)
    if zones is None:
        regional["zones"] = zone_meta
    else:
        zdata = {}
        for name, zmask in zones.items():
            vox = int(zmask.sum())
            zdata[name] = {
                "volume_ml": round(vox * voxel_volume_ml, 1),
                "percent_of_lung": round(vox / total_voxels * 100.0, 2) if total_voxels else None,
                "density": hu_statistics(hu_volume, zmask, voxel_volume_ml),
            }
        regional["zones"] = {"status": OK, "definition": zone_meta, "regions": zdata}

    bands, band_meta = pleural_distance_regions(mask, spacing)
    if bands is None:
        regional["pleural_bands"] = band_meta
    else:
        bdata = {}
        for name, bmask in bands.items():
            vox = int(bmask.sum())
            bdata[name] = {
                "volume_ml": round(vox * voxel_volume_ml, 1),
                "percent_of_lung": round(vox / total_voxels * 100.0, 2) if total_voxels else None,
                "density": hu_statistics(hu_volume, bmask, voxel_volume_ml),
            }
        regional["pleural_bands"] = {"status": OK, "definition": band_meta, "regions": bdata}
    result["regional_metrics"] = regional

    # ---- 6. left/right asymmetry ----
    if has_sides:
        lv = float(left.sum()) * voxel_volume_ml
        rv = float(right.sum()) * voxel_volume_ml
        lmean = density["left_lung"].get("mean_hu")
        rmean = density["right_lung"].get("mean_hu")
        denom = lv + rv
        vol_index = (lv - rv) / denom if denom else None
        result["asymmetry"] = {
            "status": OK,
            "volume_asymmetry_index": round(vol_index, 4) if vol_index is not None else None,
            "volume_asymmetry_definition": ("(left - right) / (left + right). Zero is symmetric; "
                                             "positive means the left lung is larger. Bounded to [-1, 1]. "
                                             "This is a descriptive geometric ratio, not a clinical score."),
            "mean_hu_difference": (round(lmean - rmean, 2)
                                    if lmean is not None and rmean is not None else None),
            "mean_hu_difference_definition": "left mean HU minus right mean HU, in Hounsfield units.",
            "caveat": (seg_stats.get("left_right_method") == "sagittal_midline_split") and
                      ("Left and right were divided at the sagittal midline because the lungs form a "
                       "single connected region. Per-side values near the mediastinum are approximate.")
                      or None,
            "provenance": _provenance("segmentation", "Derived from per-side masks and their HU statistics."),
        }
    else:
        result["asymmetry"] = _unavailable(
            "Left and right lungs were not separated for this study.",
            requires="Reliable image orientation and a separable lung mask.")

    # ---- 7/9. quantitative densitometry + located regions ----
    # Density measurements with published cut-points, clustered so each one
    # can be found in the source CT. These are measurements, not findings -
    # see density_regions.py for the distinction and the threshold sources.
    try:
        zone_masks = zones if zones is not None else None
        zone_by_slice = zone_assignment_by_slice(mask, geometry)
        dist_for_regions = None
        if bands is not None:
            sampling = (float(spacing[2]), float(spacing[1]), float(spacing[0]))
            envelope = np.empty_like(mask)
            for k in range(mask.shape[0]):
                envelope[k] = ndimage.binary_fill_holes(mask[k])
            dist_for_regions = ndimage.distance_transform_edt(envelope, sampling=sampling)

        result["densitometry"] = analyze_density_regions(
            hu_volume, mask, geometry, voxel_volume_ml,
            left_mask=left, right_mask=right,
            zones=zone_masks, zone_of_slice=zone_by_slice, dist_mm=dist_for_regions,
        )
    except Exception as exc:  # noqa: BLE001
        result["densitometry"] = _unavailable(
            f"Densitometry could not be computed: {exc}",
            requires="A valid lung segmentation and calibrated Hounsfield data.")

    # ---- sections requiring capabilities this application does not have ----
    result["lobe_metrics"] = _unavailable(
        "No lobe segmentation is implemented. The five pulmonary lobes cannot be delineated by "
        "the HU-threshold method used here, because the fissures are not reliably resolvable by "
        "density alone. Reporting lobe volumes without segmenting lobes would be fabrication.",
        requires="A fissure-aware or model-based lobe segmentation.")

    result["findings"] = {
        "status": NOT_AVAILABLE,
        "reason": ("No finding-detection method is implemented. This application performs no disease "
                   "classification and detects no radiological findings."),
        "requires": "A validated detection or segmentation model for each finding type.",
        # Structure only, so the viewer and API contract are stable when a real
        # detector is added. Deliberately empty - never populated with examples.
        "supported_finding_types": [
            "ground_glass_opacity", "reticulation", "honeycombing", "traction_bronchiectasis",
            "mosaic_attenuation", "air_trapping", "consolidation", "emphysema",
            "cystic_change", "nodule", "architectural_distortion",
        ],
        "regions": [],
        "burden": {},
    }

