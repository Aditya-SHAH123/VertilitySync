def assess_scan_quality(summary, segmentation_stats, geometry, series_status):
    """Technical adequacy of the study for quantitative analysis.

    This is an assessment of the IMAGE, not of the patient. It never
    constitutes a clinical finding.
    """
    checks = []
    warnings = []

    def add(name, status, detail, value=None):
        checks.append({"name": name, "status": status, "detail": detail, "value": value})
        if status in (WARNING, FAILED):
            warnings.append(f"{name}: {detail}")

    slice_count = summary.get("slice_count") or 0
    add("Slice count", OK if slice_count >= 40 else WARNING,
        "Enough slices for volumetric analysis." if slice_count >= 40
        else "Few slices; volumetric and zonal measurements are coarse.", slice_count)

    add("Image dimensions", OK, "Reconstructed in-plane matrix.",
        f"{summary.get('rows')} x {summary.get('columns')}")

    ps = summary.get("pixel_spacing_mm")
    add("Pixel spacing", OK if ps else NOT_AVAILABLE,
        "Read from DICOM PixelSpacing." if ps else "PixelSpacing absent; a 1 mm fallback was used for display only.",
        ps)

    ss = summary.get("slice_spacing_mm")
    add("Slice spacing", OK if ss else NOT_AVAILABLE,
        "Median inter-slice spacing." if ss else "Could not be determined.",
        round(ss, 3) if ss else None)

    st = summary.get("slice_thickness_mm")
    add("Slice thickness", OK if st is not None else NOT_AVAILABLE,
        "Read from DICOM SliceThickness." if st is not None else "SliceThickness absent from the series.", st)

    hu_status = summary.get("hu_conversion_status")
    add("Hounsfield calibration", OK if hu_status == "AVAILABLE" else (
            WARNING if hu_status == "PARTIAL" else FAILED),
        {"AVAILABLE": "Rescale slope and intercept present on every slice.",
         "PARTIAL": "Some slices lack rescale values; density measurements exclude nothing but are less reliable.",
         }.get(hu_status, "No calibrated Hounsfield data; density measurements are not meaningful."),
        hu_status)

    ori = summary.get("orientation_status", "")
    add("Image orientation", OK if ori == "AVAILABLE" else WARNING,
        "Slice order derived from patient geometry." if ori == "AVAILABLE"
        else "Fallback slice ordering was used; spatial measurements are less reliable.", ori)

    scanner = summary.get("scanner_metadata") or {}
    add("Scanner", OK if scanner else NOT_AVAILABLE,
        "Non-identifying technical metadata present."
        if scanner else "No technical scanner metadata available.",
        scanner or None)

    add("Reconstruction kernel", NOT_AVAILABLE,
        "ConvolutionKernel is not among the technical fields this application reads.", None)

    add("Contrast status", NOT_AVAILABLE,
        "Determining contrast requires metadata this application does not read, "
        "and inferring it from density alone is unreliable.", None)

    irregular = any("Irregular spacing" in w for w in (summary.get("validation_warnings") or []))
    gap = any("large gap" in w.lower() for w in (summary.get("validation_warnings") or []))
    add("Slice spacing regularity", WARNING if (irregular or gap) else OK,
        "Irregular spacing or a large inter-slice gap was detected; volumes assume uniform spacing."
        if (irregular or gap) else "Spacing is regular within tolerance.", None)

    dup = any("duplicate" in w.lower() for w in (summary.get("validation_warnings") or []))
    add("Duplicate slices", WARNING if dup else OK,
        "Duplicate SOPInstanceUIDs were dropped during validation." if dup
        else "No duplicate instances detected.", None)

    if segmentation_stats:
        touches_border = segmentation_stats.get("touches_inplane_border")
        add("Lung containment (in plane)", WARNING if touches_border else OK,
            "The lung mask reaches the edge of the field of view; the thorax may be clipped."
            if touches_border else "The lung mask lies fully inside the field of view.", None)

        truncated = segmentation_stats.get("touches_scan_range_start_or_end")
        add("Lung containment (scan range)", WARNING if truncated else OK,
            "Lung tissue reaches the first or last slice; the lungs may not be fully covered, "
            "so total volume may be underestimated." if truncated
            else "Lung tissue does not reach either end of the scan range.", None)
    else:
        add("Lung containment", NOT_EVALUATED, "Segmentation has not been run for this study.", None)

    add("Motion / artifact", NOT_EVALUATED,
        "No motion or streak-artifact metric is implemented. Not assessed rather than assumed absent.", None)

    statuses = [c["status"] for c in checks]
    if FAILED in statuses:
        overall = FAILED
    elif WARNING in statuses:
        overall = WARNING
    else:
        overall = OK

    suitable = overall != FAILED and hu_status in ("AVAILABLE", "PARTIAL")

    return {
        "status": overall,
        "suitable_for_quantitative_analysis": bool(suitable),
        "checks": checks,
        "warnings": warnings,
        "note": ("A technical assessment of the image only. It is not a clinical finding and says "
                 "nothing about the patient."),
        "provenance": _provenance("dicom_metadata", "Validation results and DICOM technical fields."),
    }


