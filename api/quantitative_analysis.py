def zone_assignment_by_slice(mask, geometry):
    """Per-slice zone label, so a region's centroid can be reported by zone."""
    n_slices = mask.shape[0]
    slice_has_lung = mask.any(axis=(1, 2))
    if not slice_has_lung.any():
        return None
    z = np.array([geometry.to_world(k, 0, 0)[2] for k in range(n_slices)], dtype=np.float64)
    lung_z = z[slice_has_lung]
    z_min, z_max = float(lung_z.min()), float(lung_z.max())
    span = z_max - z_min
    if span <= 0:
        return None
    lo_cut, hi_cut = z_min + span / 3.0, z_min + 2.0 * span / 3.0
    return ["lower" if zz < lo_cut else ("middle" if zz < hi_cut else "upper") for zz in z]


def superior_inferior_zones(mask, geometry):
    """Splits the lung mask into upper / middle / lower thirds.

    The split is made along the true superior-inferior patient axis, using
    each slice's world Z coordinate rather than its array index, so a study
    stored in either slice direction produces the same anatomical zones. The
    thirds divide the lung's own Z extent into three equal spans - this is a
    geometric convention, not an anatomical lobe boundary.
    """
    n_slices = mask.shape[0]
    slice_has_lung = mask.any(axis=(1, 2))
    if not slice_has_lung.any():
        return None, {"status": NOT_AVAILABLE, "reason": "The lung mask is empty."}

    z_of_slice = np.array([geometry.to_world(k, 0, 0)[2] for k in range(n_slices)], dtype=np.float64)
    lung_z = z_of_slice[slice_has_lung]
    z_min, z_max = float(lung_z.min()), float(lung_z.max())
    span = z_max - z_min
    if span <= 0:
        return None, {"status": NOT_AVAILABLE,
                       "reason": "The lung occupies a single slice position; zones cannot be formed."}

    lower_cut = z_min + span / 3.0
    upper_cut = z_min + 2.0 * span / 3.0

    zone_of_slice = np.full(n_slices, "", dtype=object)
    for k in range(n_slices):
        z = z_of_slice[k]
        zone_of_slice[k] = "lower" if z < lower_cut else ("middle" if z < upper_cut else "upper")

    zones = {}
    for name in ("upper", "middle", "lower"):
        sel = np.array([zone_of_slice[k] == name for k in range(n_slices)])
        zm = np.zeros_like(mask)
        zm[sel] = mask[sel]
        zones[name] = zm

    meta = {
        "status": OK,
        "axis": "patient superior-inferior (world Z)",
        "lung_z_extent_mm": [round(z_min, 2), round(z_max, 2)],
        "boundaries_mm": {"lower_middle": round(lower_cut, 2), "middle_upper": round(upper_cut, 2)},
        "definition": "The lung's own Z extent divided into three equal spans.",
    }
    return zones, meta


def pleural_distance_regions(mask, spacing_mm):
    """Splits the lung mask by distance from the pleural surface.

    A Euclidean distance transform is run INSIDE the mask with the true
    physical voxel spacing, so each voxel's value is its distance in
    millimetres to the nearest non-lung voxel - i.e. to the lung boundary.
    Peripheral means within PERIPHERAL_BAND_MM of that boundary; central is
    the remainder. Subpleural is a narrower band within the peripheral one.

    This describes position only. It carries no diagnostic meaning.
    """
    if not mask.any():
        return None, {"status": NOT_AVAILABLE, "reason": "The lung mask is empty."}

    # The distance transform must measure distance to the OUTSIDE of the lung,
    # not to the nearest hole inside it. The lung mask keeps vessel and airway
    # holes: those structures connect to the hilum, so they are not enclosed
    # in 3D and survive 3D hole filling. Running the transform on the raw mask
    # therefore measures "distance to the nearest vessel", which on a real
    # study capped the depth at 21.8 mm and classified 99.98% of the lung as
    # peripheral.
    #
    # In a single axial slice, however, a vessel appears as an isolated region
    # enclosed by lung, so a per-slice 2D fill closes it. The filled envelope
    # is used only to define the boundary; every statistic is still reported
    # over the original mask.
    envelope = np.empty_like(mask)
    for k in range(mask.shape[0]):
        envelope[k] = ndimage.binary_fill_holes(mask[k])

    # sampling order must match array axes: (slice, row, column) -> (z, y, x)
    sampling = (float(spacing_mm[2]), float(spacing_mm[1]), float(spacing_mm[0]))
    dist_mm = ndimage.distance_transform_edt(envelope, sampling=sampling)

    peripheral = mask & (dist_mm <= PERIPHERAL_BAND_MM)
    central = mask & (dist_mm > PERIPHERAL_BAND_MM)
    subpleural = mask & (dist_mm <= SUBPLEURAL_BAND_MM)

    meta = {
        "status": OK,
        "peripheral_band_mm": PERIPHERAL_BAND_MM,
        "subpleural_band_mm": SUBPLEURAL_BAND_MM,
        "definition": ("Euclidean distance to the lung boundary, computed at true physical voxel "
                       "spacing on a per-slice hole-filled envelope so internal vessel and airway "
                       "holes do not act as false boundaries. Peripheral = within the band of the "
                       "pleural surface; central = deeper than the band. Positional only."),
        "max_depth_mm": round(float(dist_mm.max()), 2),
        "envelope_voxel_excess_percent": round(
            (float(envelope.sum()) - float(mask.sum())) / float(mask.sum()) * 100.0, 3),
    }
    return {"peripheral": peripheral, "central": central, "subpleural": subpleural}, meta


